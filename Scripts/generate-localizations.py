#!/usr/bin/env python3
"""Generate native localization resources and reject missing translations or changed format arguments."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'Localization/translations.json').read_text())
languages = catalog['languages']
permission_keys = catalog['permissions']
placeholder = re.compile(r'%(?:\d+\$)?(?:\.\d+)?[@df]')

for key, translations in catalog['strings'].items():
    assert len(translations) == len(languages) - 1, key
    for language, text in zip(languages[1:], translations):
        assert text.strip(), (key, language)
        assert sorted(placeholder.findall(key)) == sorted(placeholder.findall(text)), (key, language)

# Catch new UI keys before an untranslated source string can silently ship.
used = set()
for source in [*root.glob('App/*.swift'), *root.glob('Core/*.swift')]:
    used.update(json.loads('"' + key + '"') for key in re.findall(r'L10n.text\("((?:[^"\\]|\\.)*)"', source.read_text()))
assert not used - catalog['strings'].keys(), f'Missing source keys: {used - catalog["strings"].keys()}'

def quote(value):
    return json.dumps(value, ensure_ascii=False)

for index, language in enumerate(languages):
    strings = {key: key if index == 0 else translations[index - 1] for key, translations in catalog['strings'].items()}
    directory = root / 'Core/Resources' / f'{language}.lproj'
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'Localizable.strings').write_text('// Generated by Scripts/generate-localizations.py.\n' + '\n'.join(f'{quote(key)} = {quote(value)};' for key, value in sorted(strings.items())) + '\n')
    directory = root / 'App' / f'{language}.lproj'
    directory.mkdir(parents=True, exist_ok=True)
    (directory / 'InfoPlist.strings').write_text('// Generated by Scripts/generate-localizations.py.\n' + '\n'.join(f'{quote(key)} = {quote(strings[source])};' for key, source in permission_keys.items()) + '\n')

print(f'{len(catalog["strings"])} strings × {len(languages)} languages, plus native permission prompts.')
